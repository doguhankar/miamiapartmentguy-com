-- Minimal Supabase look-alike so the real migrations can run on a scratch Postgres.
-- Mirrors: roles, auth.jwt()/auth.role(), default privileges, the pre-existing
-- leads / agent_allowlist tables, and production's is_approved_agent() (verbatim).

create role anon nologin;
create role authenticated nologin;
create role service_role nologin bypassrls;

create schema auth;
create function auth.jwt() returns jsonb language sql stable as $$
  select coalesce(nullif(current_setting('request.jwt.claims', true), ''), '{}')::jsonb
$$;
create function auth.role() returns text language sql stable as $$
  select coalesce(auth.jwt() ->> 'role', current_user)
$$;

grant usage on schema public, auth to anon, authenticated, service_role;
alter default privileges in schema public grant all on tables to anon, authenticated, service_role;
alter default privileges in schema public grant all on functions to anon, authenticated, service_role;
alter default privileges in schema public grant all on sequences to anon, authenticated, service_role;
grant execute on function auth.jwt(), auth.role() to anon, authenticated, service_role;

create publication supabase_realtime;

-- production tables the inbox depends on (only the columns it touches)
create table public.agent_allowlist (
  id bigint generated by default as identity primary key,
  email text, approved boolean, display_name text, phone text, slack_channel_id text
);
alter table public.agent_allowlist enable row level security;
create policy agent_allowlist_select_self on public.agent_allowlist
  for select to authenticated using (lower(email) = lower((auth.jwt() ->> 'email'::text)));

create table public.leads (
  id bigint generated always as identity primary key,
  created_at timestamptz default now(),
  name text, phone text, email text, stage text default 'New Lead',
  agent_id text default 'doguhankar1@gmail.com'
);
alter table public.leads enable row level security;
create policy leads_select_own_leads on public.leads for select to public
  using ((auth.role() = 'authenticated'::text) and (agent_id = (auth.jwt() ->> 'email'::text)));
create policy leads_insert_own_leads on public.leads for insert to public
  with check ((auth.role() = 'authenticated'::text) and (agent_id = (auth.jwt() ->> 'email'::text)));
create policy leads_update_own_leads on public.leads for update to public
  using ((auth.role() = 'authenticated'::text) and (agent_id = (auth.jwt() ->> 'email'::text)))
  with check ((auth.role() = 'authenticated'::text) and (agent_id = (auth.jwt() ->> 'email'::text)));

-- verbatim from production
CREATE OR REPLACE FUNCTION public.is_approved_agent()
 RETURNS boolean
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
  select exists (
    select 1 from public.agent_allowlist
    where lower(email) = lower(auth.jwt() ->> 'email') and approved = true
  );
$function$;

-- test helpers
create schema t;
grant usage on schema t to public;
create function t.as_user(p_email text) returns void language plpgsql as $$
begin
  perform set_config('request.jwt.claims', json_build_object('email', p_email, 'role', 'authenticated')::text, true);
  execute 'set local role authenticated';
end $$;
create function t.as_server() returns void language plpgsql as $$
begin
  execute 'reset role';
  perform set_config('request.jwt.claims', '', true);
end $$;
create function t.ok(cond boolean, msg text) returns void language plpgsql as $$
begin
  if not coalesce(cond, false) then raise exception 'ASSERT FAILED: %', msg; end if;
  raise notice 'PASS: %', msg;
end $$;
-- run a statement expecting a specific SQLSTATE
create function t.denied(stmt text, code text, msg text) returns void language plpgsql as $$
declare got text;
begin
  begin
    execute stmt;
    got := 'no error';
  exception when others then
    got := sqlstate;
  end;
  if got is distinct from code then
    raise exception 'ASSERT FAILED: % (expected %, got %)', msg, code, got;
  end if;
  raise notice 'PASS: %', msg;
end $$;
